-- Generate src/unicode_ranges.h from llama.cpp src/unicode-data.cpp.
-- Usage: lua5.4 scripts/gen_unicode.lua path/to/unicode-data.cpp > src/unicode_ranges.h
local path = assert(arg[1], "usage: gen_unicode.lua unicode-data.cpp")
local f = assert(io.open(path, "r"))

local ranges, ws = {}, {}
local section
for line in f:lines() do
	if line:match("unicode_ranges_flags%s*=") then
		section = "flags"
	elseif line:match("unicode_set_whitespace%s*=") then
		section = "ws"
	elseif line:match("^};") then
		section = nil
	elseif section == "flags" then
		local s, fl = line:match("^{0x(%x+), 0x(%x+)}")
		if s then
			ranges[#ranges + 1] = { tonumber(s, 16), tonumber(fl, 16) }
		end
	elseif section == "ws" then
		local c = line:match("^0x(%x+)")
		if c then
			ws[#ws + 1] = tonumber(c, 16)
		end
	end
end
f:close()
assert(#ranges > 100 and #ws > 10, "input not recognized")
assert(ranges[1][1] == 0 and ranges[#ranges][1] == 0x110000)

-- Split the ranges at each whitespace code point and set bit 0x100.
local WS = 0x100
local function flags_at(cp)
	local lo, hi = 1, #ranges
	while lo < hi do
		local mid = (lo + hi + 1) // 2
		if ranges[mid][1] <= cp then lo = mid else hi = mid - 1 end
	end
	return ranges[lo][2]
end
local points = {}
for _, r in ipairs(ranges) do points[r[1]] = true end
for _, c in ipairs(ws) do points[c] = true; points[c + 1] = true end
local starts = {}
for p in pairs(points) do starts[#starts + 1] = p end
table.sort(starts)
local wsset = {}
for _, c in ipairs(ws) do wsset[c] = true end

local out = {}
for _, s in ipairs(starts) do
	local fl = s < 0x110000 and flags_at(s) or 0
	if wsset[s] then fl = fl | WS end
	if #out == 0 or out[#out][2] ~= fl or s == 0x110000 then
		out[#out + 1] = { s, fl }
	end
end

io.write([[
/*
 * Unicode category ranges. Generated by scripts/gen_unicode.lua from
 * llama.cpp unicode-data.cpp (MIT license, (c) the llama.cpp authors).
 * Each entry holds the first code point and the flags of a range.
 */
]])
io.write(string.format("#define UNI_NRANGES\t%d\n\n", #out))
io.write("static const struct uni_range uni_ranges[UNI_NRANGES] = {\n")
for i = 1, #out, 4 do
	local row = {}
	for j = i, math.min(i + 3, #out) do
		row[#row + 1] = string.format("{ 0x%06x, 0x%03x }", out[j][1], out[j][2])
	end
	io.write("\t", table.concat(row, ", "), ",\n")
end
io.write("};\n")
